test('moving source video advances and resumes after scrolling back and browser pauses',async({page})=>{
 await page.emulateMedia({reducedMotion:'no-preference'})
 await page.goto('/')
 const video=page.locator('.context-conveyor [data-payload=video] video')
 await expect(video).toHaveJSProperty('paused',false)
 const start=await video.evaluate(v=>(v as HTMLVideoElement).currentTime)
 await expect.poll(()=>video.evaluate(v=>(v as HTMLVideoElement).currentTime)).toBeGreaterThan(start+.3)
 // A noninteractive background video must not classify an incidental pause as a user decision.
 await video.evaluate(v=>(v as HTMLVideoElement).pause())
 await expect(video).toHaveJSProperty('paused',false)
 await page.locator('#scenarios').scrollIntoViewIfNeeded()
 await expect(video).toHaveJSProperty('paused',true)
 await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}))
 await expect(video).toHaveJSProperty('paused',false)
 const resumed=await video.evaluate(v=>(v as HTMLVideoElement).currentTime)
 await expect.poll(()=>video.evaluate(v=>(v as HTMLVideoElement).currentTime)).toBeGreaterThan(resumed+.3)
})

test('real video stays live after passing the product gate and on the next cycle',async({page})=>{
 test.setTimeout(60000)
 await page.emulateMedia({reducedMotion:'no-preference'})
 await page.goto('/')
 const source=page.locator('.context-conveyor [data-payload=video] video')
 const result=page.locator('.context-conveyor [data-result=video]')
 const canvas=result.locator('canvas')
 await expect(source).toHaveJSProperty('paused',false)
 await expect.poll(()=>result.evaluate(el=>Number(getComputedStyle(el).opacity)),{timeout:20000}).toBeGreaterThan(.5)
 const frame=await canvas.evaluate(el=>(el as HTMLCanvasElement).toDataURL())
 await expect.poll(()=>canvas.evaluate(el=>(el as HTMLCanvasElement).toDataURL())).not.toBe(frame)
 await expect(source).toHaveJSProperty('paused',false)
 await expect.poll(()=>source.evaluate(el=>Number(el.parentElement!.dataset.phase)),{timeout:25000}).toBeLessThan(.1)
 await expect.poll(()=>source.evaluate(el=>Number(getComputedStyle(el.parentElement!).opacity))).toBeGreaterThan(.5)
 await expect(source).toHaveJSProperty('paused',false)
})


