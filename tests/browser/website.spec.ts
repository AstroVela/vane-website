test('audio citations play original words; waveform seek clears the excerpt boundary', async ({page}) => {
  await page.goto('/?media=audio')
  await expect(page.locator('audio')).toHaveJSProperty('paused', true)
  await page.locator('.insight-item').filter({hasText: 'Portability, in the narrator'}).click()
  await expect(page.locator('audio')).toHaveJSProperty('paused', false)
  await expect.poll(() => page.locator('audio').evaluate(e => (e as HTMLMediaElement).currentTime)).toBeGreaterThanOrEqual(3)
  const waveform = page.getByRole('slider', {name: 'Waveform playback position', exact: true})
  const bounds = await waveform.boundingBox()
  await waveform.click({position: {x: bounds!.width * 8 / 14.789, y: bounds!.height / 2}})
  await expect.poll(() => page.locator('audio').evaluate(e => (e as HTMLMediaElement).currentTime)).toBeGreaterThan(7.5)
  await expect(page.locator('audio')).toHaveJSProperty('paused', false)
  await page.getByRole('tab', {name: 'Images', exact: true}).click()
  expect(await page.locator('video,audio').evaluateAll(els => els.filter(e => !(e as HTMLMediaElement).paused).length)).toBe(0)
})
