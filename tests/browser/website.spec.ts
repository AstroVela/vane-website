test('headline, media and evidence switch together; desktop CTA remains in view', async ({page}) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.locator('.hero-experience')).toHaveAttribute('data-media', 'video')
  await expect(page.locator('.showcase-stage video')).toHaveJSProperty('paused', true)
  const ctaPosition = (await page.locator('.hero-copy .btn').boundingBox())!.y
  for (const [label, kind, word] of [['Images', 'image', 'images'], ['Audio', 'audio', 'audio'], ['Video', 'video', 'videos']]) {
    await page.getByRole('tab', {name: label, exact: true}).click()
    await expect(page.locator('h1')).toContainText(word)
    await expect(page.locator('.media-preview')).toHaveAttribute('data-modality', kind)
    await expect(page.locator('.hero-experience')).toHaveAttribute('data-rotation', 'manual')
    expect(await page.locator('.media-preview').count()).toBe(1)
    expect(Math.abs((await page.locator('.hero-copy .btn').boundingBox())!.y - ctaPosition)).toBeLessThan(1)
    expect(await page.locator('.showcase-stage').evaluate(e => e.scrollHeight <= e.clientHeight)).toBe(true)
  }
  await page.getByRole('button', {name: 'Products', exact: true}).click()
  await expect(page.locator('#nav-products a')).toHaveCount(2)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', {name: 'Products', exact: true})).toBeFocused()
  await page.setViewportSize({width: 1366, height: 768})
  const cta = await page.locator('.hero-copy .btn').boundingBox()
  expect(cta!.y + cta!.height).toBeLessThan(768)
  await mkdir('.tmp-visual-check', {recursive: true})
  await page.screenshot({path: '.tmp-visual-check/home-1366.png'})
  expect(errors).toEqual([])
})
