test('manual playback is not interrupted by related hover; task switches stop old media',async({page})=>{
  await page.emulateMedia({reducedMotion:'no-preference'})
  await page.goto('/?scenario=image-match&result=matching-video')
  await expect(page.locator('.showcase')).toHaveAttribute('data-result','matching-video')
  await expect(page.locator('.result-stage video')).toHaveJSProperty('paused',false)
  await page.locator('.related-result').filter({hasText:'related preparation'}).hover()
  const controls=page.locator('.result-stage .media-controls button')
  // Explicit pause then resume makes this a manual playback intent.
  await controls.click();if(await page.locator('.result-stage video').evaluate(e=>(e as HTMLMediaElement).paused))await controls.click()
  await page.locator('.related-result').first().hover()
  expect(await page.locator('video,audio').evaluateAll(els=>els.filter(e=>!(e as HTMLMediaElement).paused).length)).toBeLessThanOrEqual(1)
  await page.getByRole('button',{name:'Find document evidence'}).click()
  expect(await page.locator('video,audio').evaluateAll(els=>els.filter(e=>!(e as HTMLMediaElement).paused).length)).toBe(0)
})
